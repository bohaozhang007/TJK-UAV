"""Public mission interfaces. Positions: cm, yaw: degrees clockwise, world Y right."""
from dataclasses import dataclass
from typing import Protocol


class ControlLost(RuntimeError):
    pass


class MissionError(RuntimeError):
    pass


@dataclass
class Observation:
    frame_id: str
    pose: dict
    epoch: str
    rgb: object
    image_base64: str
    intrinsics: object
    world_from_camera_cm: object
    timestamp_s: float


class Robot(Protocol):
    def attach(self): ...
    def health(self): ...
    def pose(self): ...
    def wait_stopped(self): ...
    def observe(self, timings=None) -> Observation: ...
    def preview_path(self, goal, require_arrival=False, timings=None): ...
    def locate_target(self, observation, mask, timings=None): ...
    def point_is_free(self, pose, timings=None): ...
    def navigate(self, pose): ...
    def stop(self): ...
    def land(self): ...
    def close(self): ...
